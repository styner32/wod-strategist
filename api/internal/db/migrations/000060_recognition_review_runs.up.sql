CREATE TABLE recognition_review_runs (
    id BIGSERIAL PRIMARY KEY,
    session_id TEXT NOT NULL,
    profile_id BIGINT NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    client_request_id VARCHAR(128) NOT NULL,
    request_hash TEXT NOT NULL,
    task_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED','RUNNING','COMPLETED','PARTIAL','FAILED')),
    source_version TEXT NOT NULL,
    evaluation_fingerprint TEXT NOT NULL,
    source_gcs_uri TEXT NOT NULL,
    source_object TEXT NOT NULL,
    source_generation BIGINT NOT NULL CHECK (source_generation > 0),
    record_ids JSONB NOT NULL,
    start_secs DOUBLE PRECISION NOT NULL CHECK (start_secs >= 0),
    end_secs DOUBLE PRECISION NOT NULL CHECK (end_secs > start_secs),
    snapshot JSONB NOT NULL,
    batches JSONB NOT NULL DEFAULT '[]'::jsonb,
    model TEXT NOT NULL DEFAULT '',
    prompt_version TEXT NOT NULL DEFAULT '',
    prompt_hash TEXT NOT NULL DEFAULT '',
    schema_version TEXT NOT NULL DEFAULT '',
    input_tokens BIGINT,
    output_tokens BIGINT,
    total_tokens BIGINT,
    duration_ms BIGINT NOT NULL DEFAULT 0,
    safe_error TEXT NOT NULL DEFAULT '',
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (profile_id,client_request_id)
);
CREATE INDEX recognition_review_runs_session_created ON recognition_review_runs(profile_id,session_id,created_at DESC,id DESC);
CREATE UNIQUE INDEX recognition_review_runs_one_active ON recognition_review_runs(profile_id,session_id) WHERE status IN ('QUEUED','RUNNING');
